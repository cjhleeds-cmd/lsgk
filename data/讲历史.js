function buildTeachScene(data) {
  const meta = TEACH_CATEGORY_META[data.category];
  const dimensions = Object.entries(data.dimensions).map(([id, value]) => ({
    id,
    label: TEACH_DIMENSION_LABELS[id],
    keywords: value[0],
    questions: [value[1]]
  }));
  const archives = data.archives.map(item => ({ id: item[0], date: item[1], type: item[2], title: item[3], summary: item[4], keywords: item[5] }));
  const scene = {
    id: data.id, category: data.category, categoryLabel: meta?.label || data.category, mapIndex: meta?.mapIndex ?? data.mapIndex, unitIndex: data.unitIndex,
    title: data.title, unitTitle: data.unitTitle || data.title, image: data.image, periodLabel: data.period,
    catalogQuestion: data.catalogQuestion || data.headline, scene: data.scene, soundCue: data.sound,
    briefing: {
      kicker: data.kicker || "你被带进了这段历史", headline: data.headline, role: data.role,
      roleText: data.roleText, mission: data.mission, next: data.next || "先别急着下结论。去现场翻找线索，看看它们会把你带向怎样的判断。"
    },
    archives,
    archiveInstruction: data.archiveInstruction || "查看全部线索，标记至少一份\"我的依据\"",
    dossierReward: {
      title: `《${data.title}现场卷》`,
      unlocked: "你已经用具体线索连接了处境、行动、力量与结果，这份现场卷已收入你的历史卷宗。",
      pending: "现场卷仍在整理。根据引导问题再补充一条线索依据，就有机会解锁完整卷宗。"
    },
    prompt: data.prompt || data.mission,
    promptHint: data.promptHint || "先说明现场问题，再用所选线索解释行动、结果及其原因。不要罗列结论，要说清它们之间的关系。",
    guidance: data.guidance || ["现场最迫切的问题", "行动与问题怎样对应", "哪些线索支持你的判断"],
    timelineMistakes: data.timeline || [],
    timelineQuestion: data.timelineQuestion || `你讲到的这个人物、制度或事件，在${data.period}已经出现了吗？请先把它放回正确的时间位置。`,
    outcomes: TEACH_DEFAULT_OUTCOMES,
    dimensions,
    shortQuestions: data.shortQuestions || ["先用一句话说明：现场最迫切的问题是什么？", "你标记的线索中，哪条信息最能支持你的判断？它为什么能成为依据？"],
    transferQuestion: data.transfer,
    flow: data.flow || { acceptLabel: "进入角色，探索现场", reportKicker: "现在轮到你", reportHeadline: "请用线索说出判断", submitLabel: "说完了，看看历史回响", feedbackLabel: "历史回响" }
  };
  TEACH_SCENES[scene.id] = scene;
  return scene;
}

